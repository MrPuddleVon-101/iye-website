/** An "open" item whose deadline has passed is treated as closed. */
export function effectiveStatus(o: Opportunity, now = new Date()): Opportunity['status'] {
  if (o.status === 'open' && o.deadline && new Date(`${o.deadline}T23:59:59`) < now) return 'closed';
  return o.status;
}

/** Open first, then by how soon the usual window starts from this month. */
export function soonestFirst(list: Opportunity[], now = new Date()) {
  const m = now.getMonth() + 1;
  const wait = (o: Opportunity) => (o.months.length ? Math.min(...o.months.map((x) => (x - m + 12) % 12)) : 13);
  const open = (o: Opportunity) => Number(effectiveStatus(o, now) === 'open');
  return [...list].sort((a, b) => open(b) - open(a) || wait(a) - wait(b));
}

